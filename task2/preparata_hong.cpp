// Малая константа для безопасного сравнения вещественных чисел с плавающей точкой
const double EPS = 1e-9;

// Число Пи для геометрических расчетов в радианах
const double PI_CONST = 3.14159265358979323846;

// Структура, представляющая точку на плоскости с координатами X и Y
struct Point {
    // Вещественная координата X точки
    double x;
    // Вещественная координата Y точки
    double y;

    // Конструктор по умолчанию: создает точку с координатами (0.0, 0.0)
    Point() : x(0.0), y(0.0) {}

    // Конструктор с параметрами: принимает координаты x_val и y_val
    Point(double x_val, double y_val) : x(x_val), y(y_val) {}

    // Оператор "меньше" для упорядочивания точек: сначала по возрастанию X, затем по возрастанию Y
    bool operator<(const Point& other) const {
        // Проверяем, различаются ли координаты X точек с учетом машинной погрешности
        if (std::abs(x - other.x) > EPS) {
            // Если координаты X разные, сравниваем их напрямую
            return x < other.x;
        }
        // Если координаты X совпадают, упорядочиваем по возрастанию координаты Y
        return y < other.y;
    }

    // Оператор проверки равенства двух точек
    bool operator==(const Point& other) const {
        // Точки равны, если их X и Y различаются не более чем на величину EPS
        return (std::abs(x - other.x) <= EPS) && (std::abs(y - other.y) <= EPS);
    }

    // Оператор проверки неравенства двух точек
    bool operator!=(const Point& other) const {
        // Возвращает противоположный результат оператора равенства
        return !(*this == other);
    }
};

// Функция вычисления косого (векторного) произведения векторов (B - A) и (C - A)
// Результат определяет ориентацию поворота при переходе от отрезка AB к отрезку BC:
// > 0: левый поворот (против часовой стрелки, CCW)
// < 0: правый поворот (по часовой стрелке, CW)
// == 0: точки лежат на одной прямой (коллинеарны)
inline double cross_product(const Point& a, const Point& b, const Point& c) {
    // Считаем разность произведений координат по формуле определителя второго порядка
    return (b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x);
}

// Функция удаления лишних точек, лежащих строго на ребрах выпуклой оболочки (коллинеарных)
// Согласно определению задачи, вершинами оболочки являются только крайние точки
std::vector<Point> clean_collinear_points(const std::vector<Point>& hull) {
    // Если в оболочке меньше трех вершин, промежуточных точек быть не может
    if (hull.size() < 3) {
        // Возвращаем исходную оболочку без изменений
        return hull;
    }
    // Вектор для сохранения только истинных угловых вершин
    std::vector<Point> cleaned;
    // Количество вершин в исходном многоугольнике
    int n = static_cast<int>(hull.size());
    // Обходим все вершины многоугольника по порядку
    for (int i = 0; i < n; ++i) {
        // Текущая рассматриваемая вершина
        Point current = hull[i];
        // Пока в результате есть хотя бы 2 вершины и добавление текущей не дает строго левого поворота
        while (cleaned.size() >= 2 && cross_product(cleaned[cleaned.size() - 2], cleaned.back(), current) <= EPS) {
            // Удаляем промежуточную точку, так как она лежит на ребре или внутри
            cleaned.pop_back();
        }
        // Добавляем текущую вершину в цепочку
        cleaned.push_back(current);
    }
    // Проверяем замыкание многоугольника на стыке последней, первой и второй вершин
    while (cleaned.size() >= 3 && cross_product(cleaned[cleaned.size() - 2], cleaned.back(), cleaned[0]) <= EPS) {
        // Удаляем последнюю вершину, если она коллинеарна с первой и предпоследней
        cleaned.pop_back();
    }
    // Проверяем первую вершину относительно последней и второй
    while (cleaned.size() >= 3 && cross_product(cleaned.back(), cleaned[0], cleaned[1]) <= EPS) {
        // Удаляем первую вершину со сдвигом массива
        cleaned.erase(cleaned.begin());
    }
    // Возвращаем итоговый очищенный многоугольник
    return cleaned;
}

// ============================================================================
// АЛГОРИТМ 1: Алгоритм Эндрю (Monotone Chain) - модификация алгоритма Грэхема
// Сложность: O(N log N). Используется как эталонный последовательный алгоритм.
// ============================================================================
std::vector<Point> andrew_monotone_chain(std::vector<Point> points) {
    // Получаем общее количество входных точек
    int n = static_cast<int>(points.size());
    // Если точек 1 или меньше, выпуклая оболочка состоит из них же
    if (n <= 1) {
        // Возвращаем исходный вектор
        return points;
    }
    // Сортируем все точки по возрастанию координаты X (и по Y при равенстве X)
    std::sort(points.begin(), points.end());
    // Удаляем дублирующиеся точки
    points.erase(std::unique(points.begin(), points.end()), points.end());
    // Обновляем количество уникальных точек
    n = static_cast<int>(points.size());
    // Если после удаления повторов осталось 2 точки или меньше
    if (n <= 2) {
        // Возвращаем оставшиеся точки
        return points;
    }

    // Вектор для хранения вершин выпуклой оболочки
    std::vector<Point> hull;
    // Резервируем память под 2 * n точек, чтобы избежать лишних аллокаций
    hull.reserve(2 * n);

    // Строим нижнюю цепочку выпуклой оболочки (обход слева направо)
    for (int i = 0; i < n; ++i) {
        // Пока в цепочке есть хотя бы 2 точки и поворот не строго влево
        while (hull.size() >= 2 && cross_product(hull[hull.size() - 2], hull.back(), points[i]) <= EPS) {
            // Удаляем точку с вершины стека
            hull.pop_back();
        }
        // Добавляем текущую точку в нижнюю цепочку
        hull.push_back(points[i]);
    }

    // Запоминаем размер нижней цепочки оболочки
    size_t lower_size = hull.size();

    // Строим верхнюю цепочку выпуклой оболочки (обход справа налево)
    for (int i = n - 2; i >= 0; --i) {
        // Пока в верхней цепочке есть точки и поворот не строго влево
        while (hull.size() > lower_size && cross_product(hull[hull.size() - 2], hull.back(), points[i]) <= EPS) {
            // Удаляем точку с вершины стека
            hull.pop_back();
        }
        // Добавляем текущую точку в верхнюю цепочку
        hull.push_back(points[i]);
    }

    // Удаляем последнюю точку, так как она дублирует первую точку оболочки
    hull.pop_back();

    // Возвращаем вершины выпуклой оболочки в порядке против часовой стрелки
    return hull;
}

// ============================================================================
// Процедура слияния (Merge) двух выпуклых оболочек для алгоритма Препараты-Хонга
// Точно реализует методические указания (Раздел 2.1, Рис. 2):
// L - левый многоугольник, R - правый многоугольник.
// Находятся верхняя общая опорная прямая и нижняя общая опорная прямая,
// после чего участки цепочек соединяются в единый кольцевой список.
// ============================================================================
std::vector<Point> merge_hulls(const std::vector<Point>& L, const std::vector<Point>& R) {
    // Если левая оболочка пуста, результатом является правая оболочка
    if (L.empty()) return R;
    // Если правая оболочка пуста, результатом является левая оболочка
    if (R.empty()) return L;

    // Количество вершин в левом многоугольнике L
    int n = static_cast<int>(L.size());
    // Количество вершин в правом многоугольнике R
    int m = static_cast<int>(R.size());

    // Проверяем вырожденный случай: все точки обоих многоугольников лежат на одной вертикальной прямой
    bool all_vertical = true;
    // Фиксируем координату X первой вершины
    double base_x = L[0].x;
    // Проверяем все вершины левого многоугольника L
    for (int i = 0; i < n; ++i) {
        // Если координата X отличается от базовой
        if (std::abs(L[i].x - base_x) > EPS) {
            // Точки не лежат на одной вертикали
            all_vertical = false;
            // Прерываем проверку
            break;
        }
    }
    // Если в L все точки вертикальны, проверяем вершины R
    if (all_vertical) {
        // Проходим по всем вершинам правого многоугольника R
        for (int j = 0; j < m; ++j) {
            // Если координата X отличается от базовой
            if (std::abs(R[j].x - base_x) > EPS) {
                // Точки не лежат на одной вертикали
                all_vertical = false;
                // Прерываем проверку
                break;
            }
        }
    }
    // Если действительно все точки лежат на одной вертикальной линии
    if (all_vertical) {
        // Инициализируем минимальную точку первой точкой L
        Point min_pt = L[0];
        // Инициализируем максимальную точку первой точкой L
        Point max_pt = L[0];
        // Ищем точки с минимальным и максимальным Y среди вершин L
        for (const auto& pt : L) {
            // Обновляем минимум по Y
            if (pt.y < min_pt.y) min_pt = pt;
            // Обновляем максимум по Y
            if (pt.y > max_pt.y) max_pt = pt;
        }
        // Ищем точки с минимальным и максимальным Y среди вершин R
        for (const auto& pt : R) {
            // Обновляем минимум по Y
            if (pt.y < min_pt.y) min_pt = pt;
            // Обновляем максимум по Y
            if (pt.y > max_pt.y) max_pt = pt;
        }
        // Если точки не совпадают, выпуклой оболочкой является отрезок
        if (min_pt != max_pt) return {min_pt, max_pt};
        // Если совпадают, оболочкой является одна точка
        return {min_pt};
    }

    // Ищем самую правую вершину в многоугольнике L (максимальный X, при равенстве - максимальный Y)
    int ia = 0;
    // Перебираем все вершины левого многоугольника L
    for (int i = 1; i < n; ++i) {
        // Если координата X строго больше или X равны, но Y больше
        if (L[i].x > L[ia].x + EPS || (std::abs(L[i].x - L[ia].x) <= EPS && L[i].y > L[ia].y)) {
            // Запоминаем новый индекс крайней правой вершины
            ia = i;
        }
    }

    // Ищем самую левую вершину в многоугольнике R (минимальный X, при равенстве - минимальный Y)
    int ib = 0;
    // Перебираем все вершины правого многоугольника R
    for (int j = 1; j < m; ++j) {
        // Если координата X строго меньше или X равны, но Y меньше
        if (R[j].x < R[ib].x - EPS || (std::abs(R[j].x - R[ib].x) <= EPS && R[j].y < R[ib].y)) {
            // Запоминаем новый индекс крайней левой вершины
            ib = j;
        }
    }

    // ------------------------------------------------------------------------
    // Поиск ВЕРХНЕЙ общей опорной прямой (проходящей через ltop и rtop)
    // По методичке: оба многоугольника должны лежать под этой прямой.
    // Если соседняя вершина лежит над прямой, опорная точка сдвигается к ней.
    // ------------------------------------------------------------------------
    // Начальное приближение точки касания на левом многоугольнике
    int ltop = ia;
    // Начальное приближение точки касания на правом многоугольнике
    int rtop = ib;
    // Флаг остановки итерационного процесса
    bool done_top = false;
    // Итерационный подъем к верхней опорной прямой
    while (!done_top) {
        // Предполагаем, что верхняя опорная прямая найдена
        done_top = true;
        // Проверяем соседа в R при движении по часовой стрелке (предыдущая вершина):
        // Если предыдущая вершина R лежит выше текущей прямой ltop -> rtop
        while (m > 1 && cross_product(L[ltop], R[rtop], R[(rtop - 1 + m) % m]) > EPS) {
            // Сдвигаем rtop к этой вершине
            rtop = (rtop - 1 + m) % m;
            // Процесс еще не окончен, был сделан шаг
            done_top = false;
        }
        // Проверяем соседа в L при движении против часовой стрелки (следующая вершина):
        // Если следующая вершина L лежит выше текущей прямой ltop -> rtop
        while (n > 1 && cross_product(L[ltop], R[rtop], L[(ltop + 1) % n]) > EPS) {
            // Сдвигаем ltop к этой вершине
            ltop = (ltop + 1) % n;
            // Процесс еще не окончен, был сделан шаг
            done_top = false;
        }
    }

    // ------------------------------------------------------------------------
    // Поиск НИЖНЕЙ общей опорной прямой (проходящей через lbot и rbot)
    // По методичке: оба многоугольника должны лежать над этой прямой.
    // Если соседняя вершина лежит под прямой, опорная точка сдвигается к ней.
    // ------------------------------------------------------------------------
    // Начальное приближение нижней точки касания на левом многоугольнике
    int lbot = ia;
    // Начальное приближение нижней точки касания на правом многоугольнике
    int rbot = ib;
    // Флаг остановки итерационного процесса
    bool done_bot = false;
    // Итерационный спуск к нижней опорной прямой
    while (!done_bot) {
        // Предполагаем, что нижняя опорная прямая найдена
        done_bot = true;
        // Проверяем соседа в R при движении против часовой стрелки (следующая вершина):
        // Если следующая вершина R лежит ниже текущей прямой lbot -> rbot
        while (m > 1 && cross_product(L[lbot], R[rbot], R[(rbot + 1) % m]) < -EPS) {
            // Сдвигаем rbot к этой вершине
            rbot = (rbot + 1) % m;
            // Процесс еще не окончен, был сделан шаг
            done_bot = false;
        }
        // Проверяем соседа в L при движении по часовой стрелке (предыдущая вершина):
        // Если предыдущая вершина L лежит ниже текущей прямой lbot -> rbot
        while (n > 1 && cross_product(L[lbot], R[rbot], L[(lbot - 1 + n) % n]) < -EPS) {
            // Сдвигаем lbot к этой вершине
            lbot = (lbot - 1 + n) % n;
            // Процесс еще не окончен, был сделан шаг
            done_bot = false;
        }
    }

    // ------------------------------------------------------------------------
    // Объединение вершин в итоговую выпуклую оболочку в порядке против часовой стрелки:
    // По методичке (стр. 6):
    // "вершины R от rbottom до rtop и вершины L от ltop до lbottom"
    // ------------------------------------------------------------------------
    // Вектор для объединенной оболочки
    std::vector<Point> merged;
    // Заранее выделяем емкость под все вершины обоих многоугольников
    merged.reserve(n + m);

    // Добавляем вершины правого многоугольника R от rbot до rtop (против часовой стрелки)
    int cur_r = rbot;
    // Добавляем стартовую точку rbot
    merged.push_back(R[cur_r]);
    // Цикл по кругу до достижения rtop
    while (cur_r != rtop) {
        // Переходим к следующей вершине против часовой стрелки
        cur_r = (cur_r + 1) % m;
        // Добавляем вершину в результирующий вектор
        merged.push_back(R[cur_r]);
    }

    // Добавляем вершины левого многоугольника L от ltop до lbot (против часовой стрелки)
    int cur_l = ltop;
    // Добавляем стартовую точку ltop
    merged.push_back(L[cur_l]);
    // Цикл по кругу до достижения lbot
    while (cur_l != lbot) {
        // Переходим к следующей вершине против часовой стрелки
        cur_l = (cur_l + 1) % n;
        // Добавляем вершину в результирующий вектор
        merged.push_back(L[cur_l]);
    }

    // Очищаем результат от возможных лишних промежуточных коллинеарных вершин на мостах
    return clean_collinear_points(merged);
}

// ============================================================================
// Вспомогательная рекурсивная функция для последовательного Препараты-Хонга
// ============================================================================
std::vector<Point> preparata_hong_recursive(const std::vector<Point>& points, int left, int right) {
    // Количество точек в текущем подмножестве
    int count = right - left + 1;
    // Базовый случай 1: ровно 1 точка
    if (count <= 1) {
        // Оболочка состоит из одной точки
        return {points[left]};
    }
    // Базовый случай 2: ровно 2 точки
    if (count == 2) {
        // Если точки не совпадают, обе являются вершинами оболочки
        if (points[left] != points[right]) {
            // Возвращаем отрезок из двух точек
            return {points[left], points[right]};
        }
        // Если точки совпадают, возвращаем одну
        return {points[left]};
    }
    // Базовый случай 3: ровно 3 точки
    if (count == 3) {
        // Для трех точек строим базовую оболочку через алгоритм Эндрю
        std::vector<Point> small_set = {points[left], points[left + 1], points[right]};
        // Возвращаем результат
        return andrew_monotone_chain(small_set);
    }

    // Проверяем случай, когда все точки в диапазоне имеют строго одинаковую координату X
    if (std::abs(points[left].x - points[right].x) <= EPS) {
        // Инициализируем минимум точкой с координатой left
        Point min_y_pt = points[left];
        // Инициализируем максимум точкой с координатой left
        Point max_y_pt = points[left];
        // Проходим по всем точкам текущего отрезка
        for (int i = left; i <= right; ++i) {
            // Обновляем точку с минимальным Y
            if (points[i].y < min_y_pt.y) min_y_pt = points[i];
            // Обновляем точку с максимальным Y
            if (points[i].y > max_y_pt.y) max_y_pt = points[i];
        }
        // Если точки с мин и макс Y различны, возвращаем отрезок
        if (min_y_pt != max_y_pt) return {min_y_pt, max_y_pt};
        // Иначе возвращаем одну точку
        return {min_y_pt};
    }

    // Находим геометрическую середину массива точек
    int mid = left + (right - left) / 2;

    // Корректируем границу разделения mid, чтобы точки с одинаковым X не попали и в L, и в R
    if (std::abs(points[mid].x - points[mid + 1].x) <= EPS) {
        // Запоминаем значение X на границе
        double bound_val = points[mid].x;
        // Ищем границу слева от середины
        int left_cand = mid;
        // Смещаемся влево, пока X совпадает с граничным
        while (left_cand >= left && std::abs(points[left_cand].x - bound_val) <= EPS) {
            // Двигаемся влево
            left_cand--;
        }
        // Ищем границу справа от середины
        int right_cand = mid + 1;
        // Смещаемся вправо, пока X совпадает с граничным
        while (right_cand <= right && std::abs(points[right_cand].x - bound_val) <= EPS) {
            // Двигаемся вправо
            right_cand++;
        }
        // Выбираем наиболее симметричный вариант разбиения
        if (left_cand >= left) {
            // Разделяем по левой границе
            mid = left_cand;
        } else if (right_cand <= right) {
            // Разделяем по правой границе
            mid = right_cand - 1;
        }
    }

    // Рекурсивно строим выпуклую оболочку L для левой половины точек
    std::vector<Point> hull_L = preparata_hong_recursive(points, left, mid);
    // Рекурсивно строим выпуклую оболочку R для правой половины точек
    std::vector<Point> hull_R = preparata_hong_recursive(points, mid + 1, right);

    // Объединяем выпуклые оболочки L и R с помощью процедуры слияния Препараты-Хонга
    return merge_hulls(hull_L, hull_R);
}

// ============================================================================
// АЛГОРИТМ 2: Последовательный алгоритм Препараты-Хонга (Divide-and-Conquer)
// Сложность: O(N log N).
// ============================================================================
std::vector<Point> preparata_hong_sequential(std::vector<Point> points) {
    // Если точек 1 или 0, сразу возвращаем их
    if (points.size() <= 1) return points;
    // Сортируем точки по возрастанию X, а при равенстве - по возрастанию Y
    std::sort(points.begin(), points.end());
    // Удаляем совпадающие дубликаты точек
    points.erase(std::unique(points.begin(), points.end()), points.end());
    // Запускаем рекурсивное построение методом "разделяй и властвуй"
    return preparata_hong_recursive(points, 0, static_cast<int>(points.size()) - 1);
}

// ============================================================================
// Вспомогательная функция быстрой параллельной сортировки точек на OpenMP
// ============================================================================
void parallel_quicksort_points(Point* arr, int n, int depth = 0) {
    // Для небольших отрезков или большой глубины рекурсии используем быструю стандартную сортировку
    if (n <= 10000 || depth >= 4) {
        // Сортируем локальный отрезок стандартной сортировкой
        std::sort(arr, arr + n);
        // Завершаем рекурсию
        return;
    }
    // Выбираем опорный элемент (pivot) в середине отрезка
    Point pivot = arr[n / 2];
    // Указатель на начало отрезка
    Point* left_ptr = arr;
    // Указатель на конец отрезка
    Point* right_ptr = arr + n - 1;
    // Процедура разделения элементов вокруг опорного (схема Хоара)
    while (left_ptr <= right_ptr) {
        // Двигаем левый указатель, пока элементы строго меньше опорного
        while (*left_ptr < pivot) left_ptr++;
        // Двигаем правый указатель, пока элементы строго больше опорного
        while (pivot < *right_ptr) right_ptr--;
        // Если указатели не разошлись, меняем элементы местами
        if (left_ptr <= right_ptr) {
            // Обмениваем значения элементов
            std::swap(*left_ptr, *right_ptr);
            // Продвигаем левый указатель вперед
            left_ptr++;
            // Продвигаем правый указатель назад
            right_ptr--;
        }
    }
    // Длина левого подмассива
    int left_length = static_cast<int>(right_ptr - arr + 1);
    // Длина правого подмассива
    int right_length = static_cast<int>(arr + n - left_ptr);

    // Запускаем сортировку левой части как параллельную задачу OpenMP
    #pragma omp task shared(arr) if(left_length > 10000)
    parallel_quicksort_points(arr, left_length, depth + 1);

    // Запускаем сортировку правой части как параллельную задачу OpenMP
    #pragma omp task shared(left_ptr) if(right_length > 10000)
    parallel_quicksort_points(left_ptr, right_length, depth + 1);

    // Ожидаем завершения обеих параллельных подзадач
    #pragma omp taskwait
}

// ============================================================================
// АЛГОРИТМ 3: Параллельный алгоритм Препараты-Хонга на OpenMP
// Разбивает отсортированный массив точек на P независимых блоков между потоками,
// каждый поток параллельно строит локальную выпуклую оболочку своего блока,
// после чего оболочки объединяются по схеме параллельного дерева редукции (double buffer).
// ============================================================================
std::vector<Point> preparata_hong_parallel(std::vector<Point> points, int num_threads) {
    // Получаем общее количество входных точек
    int n = static_cast<int>(points.size());
    // Если точек мало или задан только 1 поток, запускаем последовательную версию
    if (n <= 100 || num_threads <= 1) {
        // Возвращаем результат последовательного алгоритма
        return preparata_hong_sequential(points);
    }

    // Устанавливаем требуемое количество потоков для параллельной области OpenMP
    omp_set_num_threads(num_threads);

    // Параллельная сортировка точек по координате X (и Y при равенстве)
    #pragma omp parallel num_threads(num_threads)
    {
        // Только один главный поток инициирует параллельную задачу быстрой сортировки
        #pragma omp single
        {
            // Запускаем параллельную быструю сортировку массива точек
            parallel_quicksort_points(points.data(), n);
        }
    }

    // Удаляем дубликаты точек после сортировки
    points.erase(std::unique(points.begin(), points.end()), points.end());
    // Обновляем количество уникальных точек
    n = static_cast<int>(points.size());
    // Если после удаления дубликатов точек мало, строим оболочку малого размера
    if (n <= 3) {
        // Возвращаем оболочку малого размера
        return andrew_monotone_chain(points);
    }

    // Определяем фактическое количество рабочих потоков
    int actual_threads = std::min(num_threads, std::max(1, n / 10));

    // Массив векторов для хранения локальных выпуклых оболочек каждого потока
    std::vector<std::vector<Point>> current_hulls(actual_threads);
    // Массив индексов начала блоков для каждого потока
    std::vector<int> chunk_starts(actual_threads);
    // Массив индексов конца блоков для каждого потока
    std::vector<int> chunk_ends(actual_threads);

    // Разбиваем весь отсортированный массив точек на actual_threads непересекающихся частей
    for (int t = 0; t < actual_threads; ++t) {
        // Начальный индекс отрезка для потока t
        chunk_starts[t] = static_cast<int>((static_cast<long long>(t) * n) / actual_threads);
        // Конечный индекс отрезка для потока t
        chunk_ends[t] = static_cast<int>((static_cast<long long>(t + 1) * n) / actual_threads - 1);
    }

    // Параллельный цикл OpenMP: каждый поток независимо строит выпуклую оболочку своего диапазона
    #pragma omp parallel for schedule(static) num_threads(actual_threads)
    for (int t = 0; t < actual_threads; ++t) {
        // Поток t строит локальную выпуклую оболочку на отрезке [chunk_starts[t], chunk_ends[t]]
        current_hulls[t] = preparata_hong_recursive(points, chunk_starts[t], chunk_ends[t]);
    }

    // Многоуровневое параллельное объединение локальных оболочек по дереву редукции
    // Используется двойная буферизация (current_hulls -> next_hulls) для исключения race condition
    while (current_hulls.size() > 1) {
        // Текущее количество активных оболочек на данном уровне дерева
        int m = static_cast<int>(current_hulls.size());
        // Количество независимых пар для параллельного слияния
        int pairs = m / 2;
        // Размер массива оболочек для следующего уровня дерева
        int next_size = pairs + (m % 2);
        // Буфер для оболочек следующего уровня дерева
        std::vector<std::vector<Point>> next_hulls(next_size);

        // Параллельное слияние каждой пары соседних оболочек
        #pragma omp parallel for schedule(dynamic) num_threads(std::min(pairs, actual_threads))
        for (int i = 0; i < pairs; ++i) {
            // Левая оболочка пары
            int left_i = 2 * i;
            // Правая оболочка пары
            int right_i = 2 * i + 1;
            // Объединяем пару методом Препараты-Хонга и сохраняем в ячейку i нового буфера
            next_hulls[i] = merge_hulls(current_hulls[left_i], current_hulls[right_i]);
        }

        // Если число оболочек на уровне было нечетным, переносим последнюю оставшуюся без пары оболочку
        if (m % 2 != 0) {
            // Копируем непарную оболочку на следующий уровень
            next_hulls[pairs] = current_hulls.back();
        }

        // Перемещаем сформированные оболочки на место текущих для следующей итерации дерева
        current_hulls = std::move(next_hulls);
    }

    // Итоговая глобальная выпуклая оболочка находится в единственном оставшемся элементе
    return current_hulls[0];
}

// ============================================================================
// Вспомогательная функция генерации тестовых наборов точек различных распределений
// ============================================================================
std::vector<Point> generate_test_points(int n, const std::string& distribution) {
    // Создаем вектор под n точек
    std::vector<Point> pts(n);
    // Инициализируем генератор случайных чисел фиксированным сидом для воспроизводимости
    std::mt19937_64 rng(42);

    // Распределение 1: Точки равномерно распределены внутри квадрата [-1000, 1000]
    if (distribution == "square") {
        // Равномерное распределение от -1000 до +1000
        std::uniform_real_distribution<double> dist(-1000.0, 1000.0);
        // Генерируем координаты точек
        for (int i = 0; i < n; ++i) {
            // Случайная координата X
            pts[i].x = dist(rng);
            // Случайная координата Y
            pts[i].y = dist(rng);
        }
    }
    // Распределение 2: Точки равномерно распределены внутри круга радиуса 1000
    else if (distribution == "circle") {
        // Равномерное распределение для квадрата радиуса
        std::uniform_real_distribution<double> dist_u(0.0, 1.0);
        // Равномерное распределение полярного угла от 0 до 2 * pi
        std::uniform_real_distribution<double> dist_theta(0.0, 2.0 * PI_CONST);
        // Генерируем точки в полярных координатах и переводим в декартовы
        for (int i = 0; i < n; ++i) {
            // Вычисляем радиус со сдвигом плотности (для равномерности по площади)
            double r = 1000.0 * std::sqrt(dist_u(rng));
            // Вычисляем угол
            double theta = dist_theta(rng);
            // Координата X
            pts[i].x = r * std::cos(theta);
            // Координата Y
            pts[i].y = r * std::sin(theta);
        }
    }
    // Распределение 3: Нормальное (Гауссово) распределение точек со сгущением в центре
    else {
        // Нормальное распределение с центром 0 и стандартным отклонением 400
        std::normal_distribution<double> norm_dist(0.0, 400.0);
        // Генерируем координаты точек
        for (int i = 0; i < n; ++i) {
            // Случайная координата X по нормальному закону
            pts[i].x = norm_dist(rng);
            // Случайная координата Y по нормальному закону
            pts[i].y = norm_dist(rng);
        }
    }
    // Возвращаем сформированный вектор точек
    return pts;
}

// ============================================================================
// Функция автоматического проведения серии бенчмарков и замеров производительности
// ============================================================================
void run_benchmarks(const std::string& csv_filename) {
    // Открываем выходной CSV файл для записи результатов экспериментов
    std::ofstream csv(csv_filename);
    // Записываем заголовки колонок в формате CSV
    csv << "algorithm,n,threads,distribution,time_ms,hull_size\n";

    // Набор исследуемых объемов входных данных N (от 10 тысяч до 10 миллионов)
    std::vector<int> n_sizes = {10000, 50000, 100000, 500000, 1000000, 5000000, 10000000};
    // Набор исследуемых типов распределений
    std::vector<std::string> distributions = {"square", "circle", "gaussian"};
    // Максимальное количество доступных аппаратных потоков CPU
    int max_threads = omp_get_max_threads();
    // Набор потоков для замеров масштабируемости
    std::vector<int> thread_counts;
    // Добавляем 1 поток
    thread_counts.push_back(1);
    // Добавляем 2 потока
    if (max_threads >= 2) thread_counts.push_back(2);
    // Добавляем 4 потока
    if (max_threads >= 4) thread_counts.push_back(4);
    // Добавляем 8 потоков
    if (max_threads >= 8) thread_counts.push_back(8);
    // Добавляем максимальное количество потоков
    if (std::find(thread_counts.begin(), thread_counts.end(), max_threads) == thread_counts.end()) {
        thread_counts.push_back(max_threads);
    }
    // Сортируем список потоков по возрастанию
    std::sort(thread_counts.begin(), thread_counts.end());

    // Выводим приветственное сообщение в консоль
    std::cout << "========================================================\n";
    std::cout << "   ЗАПУСК ЭКСПЕРИМЕНТОВ И СРАВНЕНИЯ ТРЕХ АЛГОРИТМОВ     \n";
    std::cout << "   Аппаратных ядер/потоков CPU: " << max_threads << "\n";
    std::cout << "========================================================\n";

    // Цикл по типам распределений точек
    for (const auto& dist : distributions) {
        // Цикл по размерам входных данных
        for (int n : n_sizes) {
            std::cout << "\n>>> Тестирование: N = " << n << ", распределение = " << dist << "\n";
            // Генерируем точки для текущего эксперимента
            auto pts = generate_test_points(n, dist);

            // 1. Тестируем Алгоритм Эндрю (Monotone Chain)
            {
                // Засекаем время начала
                auto t0 = std::chrono::high_resolution_clock::now();
                // Выполняем алгоритм
                auto hull = andrew_monotone_chain(pts);
                // Засекаем время окончания
                auto t1 = std::chrono::high_resolution_clock::now();
                // Вычисляем длительность в миллисекундах
                double ms = std::chrono::duration<double, std::milli>(t1 - t0).count();
                // Сохраняем в CSV файл
                csv << "Andrew_MonotoneChain," << n << ",1," << dist << "," << ms << "," << hull.size() << "\n";
                // Выводим результат в терминал
                std::cout << "  [1] Эндрю (Monotone Chain):       " << std::fixed << std::setprecision(2)
                          << ms << " ms (вершин: " << hull.size() << ")\n";
            }

            // 2. Тестируем последовательный алгоритм Препараты-Хонга
            {
                // Засекаем время начала
                auto t0 = std::chrono::high_resolution_clock::now();
                // Выполняем алгоритм
                auto hull = preparata_hong_sequential(pts);
                // Засекаем время окончания
                auto t1 = std::chrono::high_resolution_clock::now();
                // Вычисляем длительность в миллисекундах
                double ms = std::chrono::duration<double, std::milli>(t1 - t0).count();
                // Сохраняем в CSV файл
                csv << "PreparataHong_Sequential," << n << ",1," << dist << "," << ms << "," << hull.size() << "\n";
                // Выводим результат в терминал
                std::cout << "  [2] Препарата-Хонг (последов.):   " << std::fixed << std::setprecision(2)
                          << ms << " ms (вершин: " << hull.size() << ")\n";
            }

            // 3. Тестируем параллельный алгоритм Препараты-Хонга на OpenMP для разного числа потоков
            for (int th : thread_counts) {
                // Засекаем время начала
                auto t0 = std::chrono::high_resolution_clock::now();
                // Выполняем алгоритм с th потоками
                auto hull = preparata_hong_parallel(pts, th);
                // Засекаем время окончания
                auto t1 = std::chrono::high_resolution_clock::now();
                // Вычисляем длительность в миллисекундах
                double ms = std::chrono::duration<double, std::milli>(t1 - t0).count();
                // Сохраняем в CSV файл
                csv << "PreparataHong_OpenMP," << n << "," << th << "," << dist << "," << ms << "," << hull.size() << "\n";
                // Выводим результат в терминал
                std::cout << "  [3] Препарата-Хонг (OpenMP " << std::setw(2) << th << " пот.): "
                          << std::fixed << std::setprecision(2) << ms << " ms (вершин: " << hull.size() << ")\n";
            }
            // Принудительно сбрасываем данные на диск
            csv.flush();
        }
    }

    // Закрываем файл с результатами
    csv.close();
    std::cout << "\nЭксперименты завершены. Результаты записаны в: " << csv_filename << "\n";
}

// ============================================================================
// Главная функция программы (точка входа main)
// ============================================================================
int main(int argc, char* argv[]) {
    // Отключаем синхронизацию стандартных потоков C++ с C для максимально быстрого ввода-вывода
    std::ios_base::sync_with_stdio(false);
    // Отвязываем поток cin от cout
    std::cin.tie(nullptr);

    // Проверяем, запрошен ли режим запуска серии бенчмарков
    if (argc >= 2 && std::string(argv[1]) == "--benchmark") {
        // Имя CSV файла по умолчанию
        std::string csv_path = "benchmark_results.csv";
        // Если указан второй параметр, используем его как имя файла
        if (argc >= 3) {
            csv_path = argv[2];
        }
        // Запускаем бенчмарки
        run_benchmarks(csv_path);
        // Завершаем программу
        return 0;
    }

    // Проверяем, запрошен ли режим генерации тестовых наборов точек в файл
    if (argc >= 3 && std::string(argv[1]) == "--generate") {
        // Количество генерируемых точек
        int n_gen = std::stoi(argv[2]);
        // Тип распределения (по умолчанию square)
        std::string dist_type = (argc >= 4) ? argv[3] : "square";
        // Генерируем точки
        auto generated = generate_test_points(n_gen, dist_type);
        // Выводим число N в первой строке
        std::cout << generated.size() << "\n";
        // Выводим координаты каждой точки
        for (const auto& p : generated) {
            // Координаты X и Y через пробел
            std::cout << std::fixed << std::setprecision(6) << p.x << " " << p.y << "\n";
        }
        // Завершаем программу
        return 0;
    }

    // ========================================================================
    // Стандартный режим работы программы согласно условию задания:
    // Формат ввода:
    // 1-я строка: N (количество точек)
    // Далее N строк: xi yi (координаты точек)
    //
    // Формат вывода:
    // 1-я строка: K (количество вершин выпуклой оболочки)
    // Далее K строк: xi yi (координаты вершин в порядке обхода против часовой стрелки)
    // ========================================================================

    // Переменная для считывания количества точек N
    long long n_points = 0;
    // Считываем N из стандартного потока ввода
    if (!(std::cin >> n_points) || n_points <= 0) {
        // При некорректном N завершаем работу
        return 0;
    }

    // Вектор для хранения считанных точек
    std::vector<Point> input_points;
    // Резервируем память под n_points точек
    input_points.reserve(n_points);

    // Считываем координаты всех N точек
    for (long long i = 0; i < n_points; ++i) {
        // Переменные для координат
        double cur_x, cur_y;
        // Считываем пару чисел
        if (std::cin >> cur_x >> cur_y) {
            // Добавляем точку в вектор
            input_points.emplace_back(cur_x, cur_y);
        }
    }

    // По умолчанию используем все доступные потоки OpenMP
    int num_threads = omp_get_max_threads();
    // Если в командной строке передан аргумент числа потоков
    if (argc >= 2) {
        // Считываем число потоков из первого аргумента
        num_threads = std::stoi(argv[1]);
    }

    // Строим выпуклую оболочку с помощью параллельного алгоритма Препараты-Хонга на OpenMP
    std::vector<Point> convex_hull = preparata_hong_parallel(input_points, num_threads);

    // Выводим количество вершин выпуклой оболочки в первой строке
    std::cout << convex_hull.size() << "\n";

    // Выводим координаты вершин выпуклой оболочки в порядке обхода против часовой стрелки
    for (const auto& v : convex_hull) {
        // Выводим X и Y через пробел с точностью до 6 знаков после запятой
        std::cout << std::fixed << std::setprecision(6) << v.x << " " << v.y << "\n";
    }

    // Завершение работы программы
    return 0;
}
